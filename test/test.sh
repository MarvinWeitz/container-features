#!/usr/bin/env bash
# One-command test runner for the Dev Container Features in this repo.
#
# Runs the scenario tests (test/<feature>/scenarios.json) for each feature against local source,
# the same way CI does. No publishing or registry access needed.
#
# Requirements (already provided by this repo's dev container):
#   - Docker             -> via the docker-in-docker feature in .devcontainer/devcontainer.json
#   - @devcontainers/cli -> installed by the postCreateCommand (or on first run if missing)
#
# Usage:
#   ./test/test.sh                # test every feature in src/
#   ./test/test.sh btp-cli-tools  # test a single feature
set -e

cd "$(dirname "$0")/.."

if ! command -v devcontainer >/dev/null 2>&1; then
	echo "==> Installing @devcontainers/cli ..."
	npm install -g @devcontainers/cli
fi

if ! docker info >/dev/null 2>&1; then
	echo "ERROR: Docker is not reachable. Rebuild this dev container so docker-in-docker is active" >&2
	echo "       (Command Palette -> 'Dev Containers: Rebuild Container')." >&2
	exit 1
fi

run_single() {
	local feature="$1"
	echo "==> Testing feature: ${feature}"
	# All features use scenario-based tests (scenarios.json), so the autogenerated test is skipped.
	devcontainer features test --project-folder . --skip-autogenerated --features "${feature}"
}

if [ -n "$1" ]; then
	run_single "$1"
else
	for feature_dir in src/*/; do
		run_single "$(basename "${feature_dir}")"
	done
fi

echo "==> Done ✓"
